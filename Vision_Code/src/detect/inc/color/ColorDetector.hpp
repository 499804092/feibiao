#ifndef COLOR_DETECTOR_HPP_                                          // 防止这个头文件被重复包含（头文件保护开始）
#define COLOR_DETECTOR_HPP_                                          // 定义保护宏

// ============================================================================
// ColorDetector.hpp —— 传统视觉识别引导灯（HSV 颜色分割 + 形状筛选）
// ----------------------------------------------------------------------------
// 【算法来源】大连理工大学飞镖算法 ——【进阶版】
//
//   1) 【可选】ROI 截取：赛场镖架和引导灯的高度位置相对固定，
//      把过高/过低的部分裁掉，既能减少 cv::Mat 计算量，也能减少误识别
//   2) BGR → HSV
//   3) 引导灯是绿色 → 低阈值 (H,S,V = 40,100,100)、高阈值 (80,255,255)
//      在这两个阈值之间分割 HSV 图，只保留绿色部分
//   3.5) 【新增】门内自适应亮度切分（v_ref_ratio，0=关闭）：
//      上面的严格绿门负责"不误检"，但它会把引导灯照在周围机壳上的【暗绿光晕】
//      一起吃进来（实测掩膜变成 180x118 的近方形，长宽比 1.53，离 1.60 只差 5%）。
//      所以在门内按"自身最高亮度"的比例再切一刀，只留接近最亮的部分（= 灯本身）。
//      用比例而不是固定阈值，是因为光晕的绝对亮度随距离/曝光变化很大。
//   4) 【关键一步】掩膜填洞：引导灯的灯芯会过曝成纯白（饱和度掉到 20 左右），
//      进不了"绿色"掩膜 → 掩膜变成"中间一个大黑洞的甜甜圈"。
//      甜甜圈边界毛糙、圆度极低（实测只有 0.29），任何形状判据都会把它滤掉。
//      所以必须先把轮廓内部填实，白芯被吃进来，掩膜才是一个实心圆盘。
//      ★注意：不能用形态学闭运算代替填洞。实测 21x21 闭运算会把引导灯和
//        下方的绿色标志粘成一整块，外接框变成 191x177，反而彻底失败。
//   5) 找绿色部分的轮廓 findContours
//   6) 求每个轮廓的外接矩形，把长宽比超过 1.60 的筛掉
//      （光晕会往外扩散，外接矩形不是正方形；细长的灯带/标志条在这里被滤掉）
//   7) 算填充率 extent = 轮廓面积 / 外接矩形面积，把 < 0.45 的筛掉
//      （实心光斑实测 0.70~0.76。之所以不用圆度：发光边界是毛糙的，
//        圆度在 0.29~0.57 之间乱跳，而填充率很稳定）
//   8) 剩下的里面选**面积最大**的那个 = 基地引导灯
//      （赛场上绿色的东西本来就少，筛完基本只剩引导灯，其他都是小点，
//        所以按面积挑最大的是可靠的）
//
// 【输出】默认只返回面积最大的那一个目标，坐标是输入图的原始像素坐标。
//
// 【设计说明】参数用 Params 结构体承载，不直接依赖全局配置。
//   这样"看画面调阈值"的调试工具可以单独编译（只依赖 OpenCV），
//   不用把整个工程的配置模块拖进来。
// ============================================================================

#include <opencv2/opencv.hpp>                                        // OpenCV 主头文件：图像、颜色转换、轮廓、形态学都在这
#include <vector>                                                    // std::vector 动态数组容器

class ColorDetector {                                                // 定义"颜色识别器"类
public:
    // ------------------------------------------------------------------------
    // Params —— 识别参数（对应 config/tuning.yaml 的 "color" 节点）
    //   所有参数都能在配置里改，改完不用重新编译
    //
    //   ★这里的默认值必须和 tuning.yaml 里调好的那套【完全一致】★
    //   为什么：配置文件的路径是相对运行目录的，只要在别的目录下运行程序
    //   （或者配置被改坏），就会读不到配置、静默退回到这里的默认值。
    //   如果默认值还是老的大连理工原始值（s_min=100 / v_min=100 /
    //   min_area=10 / morph_size=3），程序不会报错，但识别结果完全是另一回事
    //   —— 实测拿引导灯照片会一个都识别不出来。已经踩过一次，务必保持一致。
    // ------------------------------------------------------------------------
    struct Params {                                                  // 参数结构体：把一堆识别参数打包在一起
        // ---- HSV 阈值（OpenCV 的 8 位图：H 0~179，S/V 0~255）----
        int h_min = 40;                                              // 色调下限：绿色从这里开始（对应色相 80°）
        int h_max = 80;                                              // 色调上限：绿色到这里结束（对应色相 160°）
        int s_min = 60;                                              // 饱和度下限：实测引导灯的绿晕 S 约 140，白芯只有 21（靠填洞补救）
        int s_max = 255;                                             // 饱和度上限：一般拉满，不限制
        int v_min = 60;                                              // 亮度下限：太暗的绿不算（滤掉阴影里的绿）
        int v_max = 255;                                             // 亮度上限：一般拉满，不限制

        // ---- 形状筛选 ----
        double aspect_max = 1.60;                                    // 外接矩形长宽比上限：超过说明不是圆形光斑
        double extent_min = 0.45;                                    // 填充率下限 = 轮廓面积/外接矩形面积（实心光斑约 0.70~0.76）
        double circularity_min = 0.0;                                // 圆度下限 circularity=4π·面积/周长²；0 = 关闭（见顶部第 7 步说明）

        // ---- 面积筛选 ----
        double min_area = 5.0;                                       // 轮廓面积下限（像素²）：比这小的当噪点丢掉
        double ref_area = 2000.0;                                    // 面积归一化基准：面积到达这个值就算"满分1.0"

        // ---- 其他 ----
        int max_targets = 1;                                         // 最多返回几个目标：算法只要面积最大的那 1 个
        int morph_size = 0;                                          // 形态学核大小；★保持 0★ 开闭运算会把引导灯和下方绿标志粘成一块

        // ---- 【新增】掩膜硬化 + 门内自适应亮度切分 ----
        //   use_hull：算面积/填充率时先用 convexHull 取凸包。
        //     为什么：第 4 步"填洞"靠 drawContours(FILLED) 重画外轮廓，
        //     但如果绿环上有一像素的漏缝，RETR_EXTERNAL 会沿着外圈绕进洞里，
        //     得到的是一条"自相交的带子"（实测 29x38 的框里面积只有 196），
        //     重画出来还是空心环 → 填充率 0.18 → 被 extent_min 判死、目标整个丢失。
        //     凸包是超集，只会把这种"因空心而误杀"的候选救回来，不会让合格的变不合格。
        //     ★只影响判据，不影响输出的外接框和质心★（框和质心仍取原轮廓，
        //     所以现有掩膜尺寸和 target.width_m 都不用重新标定）
        int use_hull = 1;                                            // 1=启用凸包算判据  0=关（退回原行为）
        //   v_ref_ratio：在严格绿门内部再切一刀，只保留"接近门内最亮"的像素。
        //     为什么：引导灯的绿光会照亮周围机壳，那一片也是绿的、只是暗，
        //     于是掩膜连成一大块近方形（实测 180x118，长宽比 1.53，离上限 1.60 只差 5%）。
        //     光晕的绝对亮度随距离/曝光变化很大，用固定 v_min 去切必然顾此失彼，
        //     所以改成按"门内自身最高亮度"的比例切 —— 远近、曝光变化都能自适应。
        //     0 = 关闭（退回原行为）；0.60 = 只保留 >= 60% 最亮度的像素
        double v_ref_ratio = 0.60;                                   // 门内自适应亮度比例；★0 = 关闭★
        //   切这一刀时用的饱和度下限。过曝的灯芯 S 只有 2~30，必须放它进来，
        //   否则只切出绿环、中间还是洞（洞最终靠第 4 步填，但环一旦断裂就填不上）。
        //   注意这里放宽是【安全】的：整块区域已经被上面的严格绿门框住，不会误检。
        int v_ref_s_min = 20;                                        // 细化时的饱和度下限（放行过曝白芯）
        //   细化只在"门里最大连通块 >= 这个面积"时才做。
        //   为什么需要这道闸：细化会把 s_min 从 60 放到 20，等于把门槛降低了；
        //   如果门里只有一个几像素的小绿点（无灯画面上的杂散绿噪声），细化会把它
        //   "养大"到能通过形状判据 → 凭空多出一个假目标。实测无灯帧上出现过
        //   6x6、面积 11px² 的假目标，就是被细化养出来的。
        //   物理上也说得通：光晕撑大掩膜只在【灯近、亮、大】的时候才发生，
        //   远距离小目标本来就没这个问题，不细化反而更稳（不会把目标越切越小）。
        double v_ref_min_area = 60.0;                                // 细化门槛：门内最大块至少这么大(px²)

        // ---- ROI：只保留高度区间 [roi_top, roi_bottom)（按图像高度的比例 0~1）----
        double roi_top = 0.0;                                        // ROI 上边界：0.0 = 从画面最顶上开始
        double roi_bottom = 1.0;                                     // ROI 下边界：1.0 = 到画面最底下结束（0和1=全图）

        static Params fromJson(const cv::FileNode &node);            // 从配置文件的 color 节点读出参数（静态工厂函数）
        void print() const;                                          // 把当前参数打印成一行，方便确认生效了没
        void sanitize();                                             // 参数自检：ROI 写反了就改回全图，别把画面裁没了
    };

    // ------------------------------------------------------------------------
    // Light —— 识别出来的一个目标
    // ------------------------------------------------------------------------
    struct Light {                                                   // 目标结构体
        double score = 0.;                                           // 归一化后的面积（0~1），下游用它给多个目标排序
        double area = 0.;                                            // 原始轮廓面积（像素²），排"最大"用的就是它
        cv::Rect2d box;                                              // 目标的外接矩形（原图坐标）
        cv::Point2d center_point;                                    // 目标的质心（原图坐标）
    };

    ColorDetector() = default;                                       // 默认构造：全部用结构体里的默认参数
    explicit ColorDetector(const Params &p) : params_(p) {           // 带参数构造：把外部传进来的参数存起来
        this->params_.sanitize();                                    // 存之前先做一次参数自检
    }

    std::vector<Light> detect(const cv::Mat &src);                   // 核心接口：识别一帧，返回目标列表（按面积从大到小）

    cv::Mat makeMask(const cv::Mat &src) const;                      // 取出二值掩膜（调 HSV 阈值时看的就是这张黑白图）

    Params       &params()       { return this->params_; }           // 取参数（可写）—— 调试工具靠它做实时调参
    const Params &params() const { return this->params_; }           // 取参数（只读版本）

private:
    Params params_;                                                  // 成员变量：本识别器使用的全部参数
};

#endif // COLOR_DETECTOR_HPP_                                          // 头文件保护结束
