// ============================================================================
// uvc_project_integration_test.cpp —— 用【工程里的真实 UvcCamera 类】取图验证
// ----------------------------------------------------------------------------
// 与 uvc_view.cpp 的区别（两个都跑，各有用处）：
//   uvc_view.cpp  → 独立验证"相机 + OpenCV"这条路通不通（不依赖工程代码）
//   本文件         → 验证【工程里的 UvcCamera 类】本身能不能工作
//
// 它用真实的 sensors::BaseCamera 接口，与 main.cpp 取图线程写法完全一致：
//     UvcCamera cam(sp);
//     cam.cameraInit();
//     cam.refreshImage(fd_msgs);
//
// 为什么要单独做这个：工程主程序 main.cpp 会起 5 个线程 + 开 OpenCV 调试窗口，
// 无桌面环境（SSH）跑不起来；本测试只走取图这一段，
// 能明确区分"是相机代码的问题"还是"工程其它部分的问题"。
//
// ---------------------------------------------------------------------------
// 编译（在 Vision_Code/build 目录下执行）：
//   g++ -std=c++20 -O2 ../verify/uvc_project_integration_test.cpp \
//            ../verify/fake_serial.cpp \
//            ../src/sensors/src/uvc/UvcCamera.cpp \
//            ../src/utility/src/function/function.cpp \
//            -o uvc_it \
//            -I../src/sensors/inc -I../src/utility/inc -I../src/threads/inc \
//            -I../config/autogenerated_flatbuffers \
//            $(pkg-config --cflags --libs opencv4) -lpthread
//
// 运行：./uvc_it
//
// ★注意：故意**不**编译 src/sensors/src/serialport/SerialPort.cpp，
//         因为要用电控假串口（fake_serial.cpp）替换掉真串口，
//         否则会卡在"等电控指令"那一步。
// ---------------------------------------------------------------------------
// ============================================================================

#include <opencv2/opencv.hpp>
#include <cstdio>

#include "uvc/UvcCamera.hpp"     // ★ 工程真实的 UVC 取图类
#include "global/Struct.hpp"
#include "lockfree/LockFree.hpp"

int main() {
    printf("========== 工程 UvcCamera 类 取图验证 ==========\n");

    SerialPort sp;                 // 假串口（实现见 fake_serial.cpp）
    UvcCamera cam(sp);             // ★ 工程真实类 ★

    cam.cameraInit();              // 打开 /dev/video0，与 main.cpp 一致

    LfStack<FromData> fd_msgs;
    fd_msgs.push(FromData{});      // refreshImage 内部是 pop+push，先放个哨兵

    const int N = 100;             // 取 100 帧
    double t0 = (double)cv::getTickCount();
    for (int i = 0; i < N; ++i) {
        cam.refreshImage(fd_msgs); // ★ 工程真实的取图调用 ★
    }
    double el = ((double)cv::getTickCount() - t0) / cv::getTickFrequency();

    auto opt = fd_msgs.pop();
    if (!opt.has_value() || opt->img.empty()) {
        printf("❌ 没取到图像\n");
        return 1;
    }

    const cv::Mat &img = opt->img;
    cv::Scalar mean, stddev;
    cv::meanStdDev(img, mean, stddev);

    printf("\n------------------ 结果 ------------------\n");
    printf("取到图像     : %d 列 x %d 行, %d 通道\n", img.cols, img.rows, img.channels());
    printf("画面均值     : B=%.1f G=%.1f R=%.1f\n", mean[0], mean[1], mean[2]);
    printf("画面标准差   : %.1f   %s\n", stddev[0],
           stddev[0] < 2.0 ? "⚠️ 接近纯色，检查镜头盖/曝光/USB 带宽" : "✓ 画面有内容");
    printf("电控指令 mode: %d  (假串口给的应是 1)\n", opt->cd.mode);
    printf("电控指令 num : %d\n", opt->cd.number);
    printf("取 %d 帧耗时 : %.2f 秒 = %.1f fps\n", N, el, N / el);

    // 顺带验证"朝向修正"参数是否真的生效：把几种朝向都存一张
    for (int mode = 0; mode <= 5; ++mode) {
        cv::Mat t;
        switch (mode) {
            case 0: t = img.clone();                                     break;
            case 1: cv::rotate(img, t, cv::ROTATE_90_CLOCKWISE);         break;
            case 2: cv::rotate(img, t, cv::ROTATE_180);                  break;
            case 3: cv::rotate(img, t, cv::ROTATE_90_COUNTERCLOCKWISE);  break;
            case 4: cv::flip(img, t, 1);                                 break;
            case 5: cv::flip(img, t, 0);                                 break;
        }
        char fn[64];
        snprintf(fn, sizeof(fn), "project_frame_orient%d.png", mode);
        cv::imwrite(fn, t);
    }
    printf("已保存 project_frame_orient0~5.png（6 种朝向各一张，挑正的那张）\n");
    printf("==========================================\n");
    return 0;
}
